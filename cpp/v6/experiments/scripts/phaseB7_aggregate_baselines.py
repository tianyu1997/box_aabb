#!/usr/bin/env python3
"""Phase B7 -- aggregate B1-B5 JSON outputs into a single LaTeX table.

Reads experiments/results_new/B{1..5}_*.json and emits
doc/generated/tab_baselines_v2.tex with mean +/- std and 5/50/95
percentiles for the columns:

    method  build_s  query_path_rad  query_time_s  SR  notes

Reproduce:

    cd cpp/v6
    python3 experiments/scripts/phaseB7_aggregate_baselines.py \\
        --inputs experiments/results_new \\
        --out doc/generated/tab_baselines_v2.tex
"""
from __future__ import annotations

import argparse
import json
import math
import statistics
from pathlib import Path

PCT = (5, 50, 95)


def percentile(xs, p):
    if not xs:
        return float("nan")
    xs = sorted(xs)
    k = (len(xs) - 1) * p / 100.0
    f = math.floor(k)
    c = math.ceil(k)
    if f == c:
        return xs[int(k)]
    return xs[f] * (c - k) + xs[c] * (k - f)


def summarise(values):
    if not values:
        return "--"
    m = statistics.mean(values)
    sd = statistics.pstdev(values) if len(values) > 1 else 0.0
    p5, p50, p95 = (percentile(values, p) for p in PCT)
    return (f"{m:.3f}$\\pm${sd:.3f} "
            f"[{p5:.3f}/{p50:.3f}/{p95:.3f}]")


def collect(path: Path) -> dict[str, list[dict]]:
    """Return {method: [cells...]}"""
    out: dict[str, list[dict]] = {}
    for jp in sorted(path.glob("B*_*.json")):
        try:
            data = json.loads(jp.read_text())
        except json.JSONDecodeError:
            continue
        if data.get("skipped"):
            continue
        method = jp.stem.split("_", 1)[1]
        out.setdefault(method, []).extend(data.get("cells", []))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--inputs", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    by_method = collect(args.inputs)
    if not by_method:
        print("[skip] no input JSONs found")
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text("% no inputs available -- run phaseB1..B5 first\n")
        return 0

    rows = []
    for method, cells in sorted(by_method.items()):
        build = [c["build_s"] for c in cells if "build_s" in c]
        rad = [c.get("query_path_rad_mean") for c in cells
               if c.get("query_path_rad_mean") is not None]
        qt = [c.get("query_time_s_mean") for c in cells
              if c.get("query_time_s_mean") is not None]
        sr = [c.get("sr") for c in cells if c.get("sr") is not None]
        rows.append((method, summarise(build), summarise(rad),
                     summarise(qt), summarise(sr)))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w") as f:
        f.write("% Auto-generated by phaseB7_aggregate_baselines.py\n")
        f.write("\\begin{tabular}{lcccc}\n\\toprule\n")
        f.write("Method & Build (s) & Path (rad) & Query (s) & SR \\\\\n")
        f.write("\\midrule\n")
        for r in rows:
            f.write(" & ".join(str(c) for c in r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print(f"[ok] wrote {args.out} ({len(rows)} methods)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
